// ---- the tool dispatcher ----------------------------------------------------
//
// 0x30D1A0 is the function that runs whatever tool is selected. It is 43 KB of
// strcmp chain - 403 of them - against every tool name in the game:
// rail_concrete, road_mud, pipe_steam, sewagepipe_4, eletric_uhigh2,
// fence_zp250, conveyor, create_cableway, factoryconnection_oneway,
// pedestrianway_brick ... and it is called from exactly ONE place, the per-frame
// UI update at 0x105F45.
//
// WHY THAT MATTERS. Layer 1's three hooks used to decide "is this question
// coming from a build tool" by testing the return address against the body of
// the shared drag-a-line tool. That covers rail, roads, pipes, water, sewage,
// heating, conveyors, fences, cableways and power lines, because they are all
// literally the same function. It does NOT cover the tools that have their own
