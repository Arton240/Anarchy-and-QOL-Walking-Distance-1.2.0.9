// AN_SITES[i].risky marks a check that is the only thing standing between the
// game and memory it does not own - the map boundary. Anarchy leaves those alone
// unless you set allow_outside_map = 1, and says so in the log.

// Which byte of the instruction carries the meaning:
//   kind 0  mov byte ptr [reg+0x315], [00]   the LAST byte, the immediate
//   kind 1  40 [32] FF                       the MIDDLE byte, the opcode
//   kind 2  [7C] 1C                          the FIRST byte, the condition
//   kind 3  41 [88] 85 ..                    the MOV opcode, store -> load
//   kind 4  C7 07 54 04 00 [00]              the message id's top byte
//
// AN_KIND_MAX and the explicit default matter because this file is generated.
// A silent `return 1` for an unknown kind would write into the wrong byte of an
// instruction that verified correctly - the one failure mode this whole design
// is built to make impossible - so an unknown kind returns something the
// caller's range check is guaranteed to reject.
#define AN_KIND_MAX 4
static inline unsigned AnPatchOffset(const AnSite* s)
{
    switch (s->kind)
    {
        case 0:  return (unsigned)(s->len - 1);
        case 1:  return 1u;
        case 2:  return 0u;
        case 3:  return 1u;                      // 41 [88] 85 ..  the MOV opcode
        case 4:  return (unsigned)(s->len - 1);  // ... 54 04 00 [00]  the imm's top byte
        default: return 0xFFFFFFFFu;
    }
}
static inline unsigned char AnOriginalByte(const AnSite* s) { return s->expect[AnPatchOffset(s)]; }

