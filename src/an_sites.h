// an_sites.h - GENERATED, and every byte in it was read out of
// SOVIET64.exe v1.1.1.9 (PE TimeDateStamp 0x6A3EB6AD). See ANARCHY-RE-FINDINGS.md.
//
// WHAT ANARCHY ACTUALLY DOES, in one paragraph. Every build tool in this game
// keeps a "can this be built here" flag and clears it when a check fails. There
// are two such flags, because there are two families of tool:
//
//   * everything you DRAG - rail, road, pipes, water, sewage, heating, power
//     lines, fences, conveyors, cableways, airroads - runs through ONE shared
//     function at 0x4FCAF0, with the flag at state+0x315. A failed check is
//         mov byte ptr [state+0x315], 0
//     and anarchy flips that final immediate byte to 1.
//
//   * everything you PLACE - buildings - runs through 0x2BADE0, where the flag
//     lives in dil for the whole validity pass. It is set at exe+0x2C9351 and a
//     failed check is
//         xor dil, dil                    40 32 FF
//     and anarchy turns that into
//         cmp dil, dil                    40 3A FF
//     ONE byte: 0x32 becomes 0x3A.
//
// WHY cmp AND NOT mov. `mov dil, dil` is also a one-byte edit and is also a
// no-op, and it is the wrong one: `xor dil, dil` WRITES FLAGS - ZF=1, PF=1,
// CF=OF=SF=0 - and MSVC emits xor-as-zero precisely because it is happy to let
// a following jcc/setcc/cmovcc consume them. `mov` writes no flags at all, so
// it would have changed which branch some of these 31 sites fall into.
// `cmp dil, dil` computes dil-dil = 0 and sets EXACTLY the same flags as the
// xor it replaces, while leaving dil alone. Same flags, same length, register
// untouched: the only thing that changes is the one thing we wanted to change.
//
// THE THIRD FAMILY, AND THE MOST IMPORTANT ONE. 1.0 patched only the checks
// that clear the valid flag themselves - and it turns out that is a minority of
// them. Of the 228 refusals the drag-a-line tool can raise, only 63 touch
// +0x315; the other 165 just record a category at +0x318 and a message id at
// +0x31C and leave it at that. "Some other infrastructure is in the way", the
// one you hit placing a power line next to a road, is one of those 165, which
// is why 1.0 did not switch it off.
//
// What converts that record into the flag is ONE instruction, at exe+0x5116FB,
// and there is exactly one `cmp dword ptr [reg+0x31C], 0` in the whole
// executable:
//
//     005116f3  cmp dword ptr [r13+0x31C], 0     ; is there a message?
//     005116fb  jl  0x511719                     ; no  -> valid
//     005116fd  mov ecx, [r13+0x318]             ; yes -> is the category one
//     00511704  lea eax, [rcx-1]                 ;        we tolerate (1..4,
//     00511707  test eax, 0xFFFFFFFC             ;        but not 3)?
//     0051170c  jne 0x511721                     ;        no  -> stay invalid
//     0051170e  cmp ecx, 3
//     00511711  je  0x511721
//     00511713  cmp byte ptr [rbp+0x48], 0
//     00511717  je  0x511721
//     00511719  mov byte ptr [r13+0x315], 1      ; VALID
//
// Turning that `jl` (0x7C) into a `jmp` (0xEB) takes the "no message" exit
// unconditionally. One byte, same length, same target. Every refusal that works
// through the record - slope, infrastructure, crossings, angles, water, the
// lot - stops mattering, and the 82 direct flips above still handle the ones
// that clear the flag by hand afterwards.
//
// AND THE OBVIOUS QUESTION: does that gate also switch off a bounds check?
// It would be a fair worry - one instruction disabling 165 refusals at once is
// exactly where a guard could hide - so it was checked rather than assumed.
// "Outside map borders!" is btf 1162, and there are exactly TWO instructions in
// the whole executable that raise it:
//
//   exe+0x2CAA6A   the building tool     -> paired with the xor at 0x2CAA74,
//                                           which is the one row below marked
//                                           risky and left alone by default
//   exe+0x51D287   the wire validator    -> followed by
//                                           mov byte ptr [rbx+0x315], r12b
//                                           a REGISTER source, so it is not one
//                                           of the 82 immediate flips and
//                                           anarchy never touches it
//
// The drag-a-line tool at 0x4FCAF0 raises 1162 nowhere at all, which makes
// sense: its cursor comes from a raycast that has to land on the terrain, so
// off-the-map is not a state it can be in. So the gate below disables no
// boundary check, and the wire tool keeps its own regardless of this setting.
//
// All three edits are a single byte. Every site is byte-checked against the
// whole instruction before anything is written, so a game update makes this
// refuse rather than corrupt an instruction boundary. A one-byte store also
// means no thread can read a partially written value - though see the note in
// anarchy.cpp about what that does and does not prove.

